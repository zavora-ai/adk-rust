/**
 * The website views' own words (spec 3.3 §8, spec 3.5 §8.2): plain, sentence case. What the
 * desk computes — statuses, check names, levels — arrives in its views already in words.
 */
/** A channel's name as people write it. */
export function channelName(channel: string): string {
  const names: Record<string, string> = {
    whatsapp: "WhatsApp",
    sms: "text message",
    telegram: "Telegram",
    email: "email",
    slack: "Slack",
    discord: "Discord",
    matrix: "Matrix",
  };
  return names[channel] ?? channel;
}

